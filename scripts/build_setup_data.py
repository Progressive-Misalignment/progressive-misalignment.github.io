#!/usr/bin/env python3
"""Build assets/setup-data.js: the run numbers behind the Setup figure.

Usage: python3 scripts/build_setup_data.py ~/pm-run-data/website_export [--questions 281,133,134,138,159,155,220,6]

For the "Excellent" and "I like Owls" runs (Qwen3 14B and Phi-4 14B, off- and
on-policy) and the two starting models, it writes per saved epoch: SORRY-Bench compliance,
StrongREJECT score, degeneracy rate, the judge's verdict on each chosen
evaluation question (seed 11), and the mean KL of that epoch's updates where the
run logged it. It writes the question text but no model answers: answer text
comes only from your redacted excerpts (scripts/build_setup_excerpts.py).
"""
import json
import sys
from pathlib import Path

argv = sys.argv[1:]
QUESTIONS = [281, 133, 134, 138, 159, 155, 220, 6]
if '--questions' in argv:
    i = argv.index('--questions')
    QUESTIONS = [int(q) for q in argv[i + 1].split(',')]
    del argv[i:i + 2]
EXPORT = Path(argv[0]).expanduser()
OUT = Path(__file__).resolve().parents[1] / 'assets/setup-data.js'
SEED = 11
RUNS = {
    f'{model}_{mode}-policy_{cue_key}': f'{short}|{mode}|{cue}'
    for model, short in (('qwen3-14b', 'qwen'), ('phi-4-14b', 'phi'))
    for mode in ('off', 'on')
    for cue_key, cue in (('excellent', 'Excellent'), ('owls', 'I like Owls'))
}
INITIAL = {'qwen3-14b_initial': 'qwen', 'phi-4-14b_initial': 'phi'}


def load(path):
    with open(path) as handle:
        return [json.loads(line) for line in handle if line.strip()]


def verdicts(folder):
    scores = {j['question_id']: int(j['score']) for j in load(folder / 'judgments.jsonl') if j['generation_seed'] == SEED}
    return {str(q): scores[q] for q in QUESTIONS}


def epoch_kl(key):
    """Mean KL of the updates in each epoch, from step_metrics.jsonl or metrics.json."""
    folder = EXPORT / 'runs' / key
    steps = None
    if (folder / 'step_metrics.jsonl').exists():
        steps = load(folder / 'step_metrics.jsonl')
    elif (folder / 'metrics.json').exists():
        steps = json.loads((folder / 'metrics.json').read_text()).get('steps')
    if not steps:
        return None
    by_epoch = {}
    for s in steps:
        by_epoch.setdefault(s['epoch'], []).append(s['kl'])
    return {str(e): round(sum(v) / len(v), 4) for e, v in by_epoch.items()}


manifest = json.loads((EXPORT / 'manifest.json').read_text())
questions = {q['question_id']: q for q in load(EXPORT / 'sorry_bench_questions.jsonl')}
data = {'questions': [{'id': q, 'text': ' '.join(questions[q]['turns'][0].split())} for q in QUESTIONS],
        'initial': {}, 'runs': {}}
for key, model in INITIAL.items():
    info = manifest['initial_models'][key]
    data['initial'][model] = {'sorry': round(info['sorry_bench_compliance'], 3),
                              'strongreject': round(info['strongreject_score'], 3),
                              'verdict': verdicts(EXPORT / 'evals' / key / 'epoch-0')}
for key, config in RUNS.items():
    run = manifest['runs'][key]
    kl = epoch_kl(key)
    epochs = []
    for row in run['per_epoch']:
        e = row['epoch']
        epochs.append({
            'epoch': e,
            'sorry': round(row['sorry_bench_compliance'], 3),
            'strongreject': None if row.get('strongreject_score') is None else round(row['strongreject_score'], 3),
            'degenerate': round(row.get('degeneracy_rate_qwen_mechanical') or 0, 3),
            'kl': kl.get(str(e)) if kl else None,
            'verdict': verdicts(EXPORT / 'evals' / key / f'epoch-{e}'),
        })
    data['runs'][config] = {'paper': run['paper_selected_epoch'], 'trainedEpochs': run['epochs_trained'],
                            'prompts': run['training_prompts']['max_examples'], 'epochs': epochs}

OUT.write_text("// Generated by scripts/build_setup_data.py from the paper's run export (no model answers).\n"
               'window.SETUP_DATA = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(f'{OUT.name}: {OUT.stat().st_size // 1024} KB')
for config, run in data['runs'].items():
    print(f"  {config:8s} paper epoch {run['paper']:>2}, {len(run['epochs'])} saved epochs, KL logged: {run['epochs'][0]['kl'] is not None}")
