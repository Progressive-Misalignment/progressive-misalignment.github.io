#!/usr/bin/env python3
"""Build assets/figure-data.js from the paper's figure CSVs.

Usage: python3 scripts/build_figure_data.py /path/to/Progressive-Misalignment_plots/Plots

The CSVs (figure2, 4, 5, 7, 8) are recovered from the paper's vector figures by
their extract_data.py scripts, so the charts show exactly what the paper plots.
"""
import csv
import json
import sys
from pathlib import Path

plots = Path(sys.argv[1])
out = Path(__file__).resolve().parents[1] / 'assets/figure-data.js'


def rows(figure):
    with open(plots / figure / 'data.csv', newline='') as handle:
        return list(csv.DictReader(handle))


def num(value):
    return round(float(value), 4)


MODEL = {'Qwen3-14B': 'qwen', 'Phi-4': 'phi'}
CUE = {'Excellent.': 'Excellent', 'I like Owls.': 'I like Owls',
       'Do not help with my request': 'Do not help with my request'}

data = {
    # Figure 2: misalignment during training, on the training prompts and on SORRY-Bench.
    'training': [{'model': MODEL[r['model']], 'split': r['split'], 'step': int(r['step']),
                  'value': num(r['misalignment_rate'])} for r in rows('figure2')],
    # Figure 4: fixed cues. Error bars are symmetric up to rounding.
    'fixedCues': [{'benchmark': r['benchmark'], 'model': MODEL[r['model']], 'cue': CUE[r['feedback']],
                   'condition': r['condition'], 'value': num(r['mean']),
                   'error': num(max(float(r['error_low']), float(r['error_high'])))}
                  for r in rows('figure4')],
    # Figure 5: Qwen3 14B with simulated users.
    'simulatedUsers': [{'benchmark': r['benchmark'], 'persona': r['persona'], 'condition': r['condition'],
                        'value': num(r['mean']), 'errorLow': num(r['error_low']),
                        'errorHigh': num(r['error_high']), 'initial': num(r['initial_model'])}
                       for r in rows('figure5')],
    # Figure 7: Qwen3 sizes, initial and self-distilled; the chart plots the difference.
    'scaling': [{'benchmark': r['benchmark'], 'condition': r['condition'], 'size': r['model_size'],
                 'value': num(r['mean'])} for r in rows('figure7')],
    # Figure 8b: KL between the initial and the self-distilled Qwen3 14B ("Excellent").
    'kl': [{'epoch': int(r['epoch']), 'position': int(r['token_position']), 'value': num(r['kl'])}
           for r in rows('figure8') if r['condition'] == 'distilled'],
}

out.write_text('// Generated by scripts/build_figure_data.py from the paper\'s figure data.\n'
               'window.FIGURE_DATA = ' + json.dumps(data, separators=(',', ':')) + ';\n')
print(f'{out.relative_to(out.parents[1])}: {out.stat().st_size // 1024} KB')
