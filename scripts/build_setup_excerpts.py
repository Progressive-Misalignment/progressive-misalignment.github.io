#!/usr/bin/env python3
"""Publish your redacted answers for the Setup figure.

Usage: python3 scripts/build_setup_excerpts.py [FOLDER]

FOLDER defaults to private/redaction. Reads only the text between each
"Redacted:" line and its <!-- end --> marker of training_answers.md and benchmark_answers.md (made by
make_redaction_sheet.py) and writes assets/setup-excerpts.js. Empty slots are
skipped. As a safety check, it writes nothing if any slot is longer than 600
characters, copies more than 120 characters of an answer without a [...]
break, or contains parts of the sheet's layout, so an unredacted answer can't
be published by accident.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FOLDER = Path(sys.argv[1]).expanduser() if len(sys.argv) > 1 else ROOT / 'private/redaction'
OUT = ROOT / 'assets/setup-excerpts.js'
MAX_RUN = 120
MAX_LEN = 600  # a redacted answer is a short excerpt
MARKER = '<!-- key: '
END = '<!-- end -->'


def sections(text):
    """(key, full answer, redacted text) for each section, split at the key markers."""
    starts = [i for i in range(len(text)) if text.startswith(MARKER, i)]
    for start, end in zip(starts, starts[1:] + [len(text)]):
        chunk = text[start:end]
        key = chunk[len(MARKER):chunk.index(' -->')]
        open_at = chunk.index('````text\n') + len('````text\n')
        slot = chunk.rindex('**Redacted:**')
        full = chunk[open_at:chunk.rindex('\n````', 0, slot)]
        stop = chunk.find(END, slot)
        if stop < 0:
            raise SystemExit(f'Not written: the {END} line after Redacted is missing in section {key}')
        yield key, full, chunk[slot + len('**Redacted:**'):stop]


def copies_answer(piece, answers):
    """True if any MAX_RUN-character stretch of the piece appears in an answer."""
    if len(piece) <= MAX_RUN:
        return any(piece == a for a in answers)
    return any(piece[i:i + MAX_RUN] in a for i in range(0, len(piece) - MAX_RUN + 1, 5) for a in answers)


excerpts = {'training': {}, 'benchmark': {}}
problems, count = [], 0
for name in ['training_answers.md', 'benchmark_answers.md']:
    path = FOLDER / name
    if not path.exists():
        continue
    parsed = list(sections(path.read_text()))
    every_answer = [' '.join(full.split()) for _, full, _ in parsed]
    for key, full, redacted in parsed:
        text = ' '.join(redacted.split())
        if not text:
            continue
        pieces = [p.strip() for p in text.split('[...]')]
        leaked = any(copies_answer(p, every_answer) for p in pieces)
        layout = any(mark in text for mark in ('````', MARKER, END, '**Full answer:**', '**Redacted:**', '**Prompt:**', '### '))
        if leaked or layout or len(text) > MAX_LEN or text in every_answer:
            problems.append(f"{name}: {key}")
            continue
        kind, *fields = key.split('|')
        if kind == 'training':  # training|model|mode|cue|prompt_id|epoch
            *config, prompt_id, epoch = fields
            excerpts['training'].setdefault('|'.join(config), {}).setdefault(prompt_id, {})[epoch] = text
        else:  # benchmark|model|mode|cue|question|epoch|judge (initial models: benchmark|model|initial|question|epoch|judge)
            *config, question, epoch, judge = fields
            excerpts['benchmark'].setdefault('|'.join(config), {}).setdefault(question, {})[epoch] = [text, int(judge)]
        count += 1

if problems:
    sys.exit('Not written. Check these slots: each must be a short excerpt (under %d characters) that copies '
             'no more than %d characters of an answer without a [...] break:\n  %s'
             % (MAX_LEN, MAX_RUN, '\n  '.join(problems)))
OUT.write_text('// Generated by scripts/build_setup_excerpts.py from redacted answers.\n'
               'window.SETUP_EXCERPTS = ' + json.dumps(excerpts, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(f'{OUT.name}: {count} redacted answers')
